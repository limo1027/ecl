    def gen_func(self, op):
        _, name, sub_code, params, varargs, kwargs, ret_type, defaults = op
        func_label = self.func_label_by_id.get(
            id(op), self.func_labels.get(name, f"func_{name}"))
        off = self.alloc_temp(f"__fn_{name}")
        label = self.get_string_label(name)
        sig_label = self._make_sig(params)
        self.emit(
            f" lea rcx, [rbp{off}]\n"
            f" lea rdx, [{label}]\n"
            f" lea r8, [{func_label}]\n"
            f" lea r9, [{sig_label}]\n"
            f" call runtime_new_function")
        if defaults:
            defaults_off = self.alloc_raw(f"__defs_{name}", len(params) * 16)
            for i, p in enumerate(params):
                pname = p['name']
                off_i = defaults_off + i * 16
                if pname not in defaults:
                    self.emit(
                        f" mov qword ptr [rbp{off_i}], -1\n"
                        f" mov qword ptr [rbp{off_i + 8}], 0")
                    continue
                val = defaults[pname]
                if p.get('type') == 'bi':
                    self.emit(f" mov qword ptr [rbp{off_i}], 0")
                    if isinstance(val, int):
                        self.emit(
                            f" mov qword ptr [rbp{off_i + 8}], {val}")
                    elif isinstance(val, bool):
                        self.emit(
                            f" mov qword ptr [rbp{off_i + 8}], {int(val)}")
                    else:
                        self.emit(
                            f" mov qword ptr [rbp{off_i + 8}], 0")
                    self.emit(f" lea rcx, [rbp{off_i}]")
                    self.emit(f" lea rdx, [rbp{off_i}]")
                    self.emit(f" call runtime_to_bi")
                elif isinstance(val, bool):
                    self.emit(
                        f" mov qword ptr [rbp{off_i}], 0\n"
                        f" mov qword ptr [rbp{off_i + 8}], {int(val)}")
                elif isinstance(val, int):
                    self.emit(
                        f" mov qword ptr [rbp{off_i}], 0\n"
                        f" mov qword ptr [rbp{off_i + 8}], {val}")
                elif isinstance(val, float):
                    flabel = self.get_float_label(val)
                    self.emit(
                        f" mov qword ptr [rbp{off_i}], 1\n"
                        f" mov rax, qword ptr [{flabel}]\n"
                        f" mov qword ptr [rbp{off_i + 8}], rax")
                elif isinstance(val, str):
                    slabel = self.get_string_label(val)
                    self.emit(
                        f" mov qword ptr [rbp{off_i}], 2\n"
                        f" lea rax, [{slabel}]\n"
                        f" mov qword ptr [rbp{off_i + 8}], rax")
                else:
                    self.emit(
                        f" mov qword ptr [rbp{off_i}], -1\n"
                        f" mov qword ptr [rbp{off_i + 8}], 0")
            self.emit(f" lea rcx, [rbp{off}]")
            self.emit(f" lea rdx, [rbp{defaults_off}]")
            self.emit(f" call runtime_func_set_defaults")
        # ★ 挂接点：闭包捕获打包（必须在 define_function 之前）
        self.gen_cap_dict(op, off, name)
        self.emit(f" lea rcx, [rbp{off}]")
        self.emit(f" lea rdx, [{label}]")
        self.emit(" call runtime_define_function")

    def gen_dll_call(self, dest, func_name, args):
        nargs = len(args)
        offd = self.alloc_temp(dest)
        spec_label = self.get_string_label(self.dll_specs[func_name])
        if nargs > 0:
            args_arr_off = self.alloc_raw(f"__dllargs_{offd}", nargs * 8)
        else:
            args_arr_off = 0
        for i, a in enumerate(args):
            aoff = self.alloc_temp(a)
            self.emit(
                f"    lea rax, [rbp{aoff}]\n"
                f"    mov qword ptr [rbp{args_arr_off + i * 8}], rax")
        self.emit(f"    lea rcx, [rbp{offd}]")
        self.emit(f"    lea rdx, [{spec_label}]")
        if nargs > 0:
            self.emit(f"    lea r8, [rbp{args_arr_off}]")
        else:
            self.emit("    xor r8, r8")
        self.emit(f"    mov r9, {nargs}")
        self.emit("    call runtime_dll_call")

    def gen_cap_dict(self, op, fn_off, name):
        caps = self.captures_by_id.get(id(op))
        if not caps:
            return
        dict_off = self.alloc_temp(f"__caps_{name}")
        self.emit(f" lea rcx, [rbp{dict_off}]")
        self.emit(" call runtime_new_dict")
        for cname in caps:
            clabel = self.get_string_label(cname)
            voff = self.alloc_temp(f"__capv_{name}_{cname}")
            koff = self.alloc_temp(f"__capk_{name}_{cname}")
            # 读全局槽当前值：get_var 返回槽指针(rax)，tag/val 分别拷出
            self.emit(f" lea rcx, [{clabel}]")
            self.emit(" call get_var")
            self.emit(" mov rdx, qword ptr [rax]")
            self.emit(f" mov qword ptr [rbp{voff}], rdx")
            self.emit(" mov rdx, qword ptr [rax + 8]")
            self.emit(f" mov qword ptr [rbp{voff + 8}], rdx")
            # key = 字符串名
            self.emit(f" mov qword ptr [rbp{koff}], 2")
            self.emit(f" lea rax, [{clabel}]")
            self.emit(f" mov qword ptr [rbp{koff + 8}], rax")
            self.emit(f" lea rcx, [rbp{dict_off}]")
            self.emit(f" lea rdx, [rbp{koff}]")
            self.emit(f" lea r8, [rbp{voff}]")
            self.emit(" call runtime_dict_set")
        # fn->captures = dict
        self.emit(f" lea rcx, [rbp{fn_off}]")
        self.emit(f" lea rdx, [rbp{dict_off}]")
        self.emit(" call runtime_func_captures")

    def gen_call(self, op):
        _, dest, func_src, args, kwargs = op
        func_name = self.temp_var_name.get(func_src)
        if isinstance(func_name, str) and func_name in self.BUILTIN_CALLS \
                and not kwargs:
            self.gen_builtin((func_name, dest, args))
            return
        if isinstance(func_name, str) and func_name in self.dll_specs \
                and not kwargs:
            self.gen_dll_call(dest, func_name, args)
            return
        nargs = len(args)
        offd = self.alloc_temp(dest)
        off_func = self.alloc_temp(func_src)
        if isinstance(func_name, str) and func_name in self.int_funcs \
                and not kwargs and nargs <= 4:
            if func_name not in self.funcs_with_defaults:
                regs = ['rcx', 'rdx', 'r8', 'r9']
                for i, a in enumerate(args):
                    aoff = self.alloc_temp(a)
                    self.emit(
                        f"    mov {regs[i]}, qword ptr [rbp{aoff + 8}]")
                self.emit(f"    call func_{func_name}__int")
                self.emit(
                    f"    mov qword ptr [rbp{offd}], 0\n"
                    f"    mov qword ptr [rbp{offd + 8}], rax")
                return
        direct_label = None
        if isinstance(func_name, str) and func_name in self.func_labels \
                and isinstance(self.func_labels[func_name], str) and not kwargs:
            if func_name not in self.funcs_with_defaults:
                direct_label = self.func_labels[func_name]
        if nargs > 0:
            args_arr_off = self.alloc_raw(f"__argsarr_{offd}", nargs * 8)
        else:
            args_arr_off = 0
        for i, a in enumerate(args):
            aoff = self.alloc_temp(a)
            self.emit(
                f"    lea rax, [rbp{aoff}]\n"
                f"    mov qword ptr [rbp{args_arr_off + i * 8}], rax")
        kw_off = 0
        kw_pair_off = 0
        if kwargs:
            kw_off = self.alloc_temp(f"__kw_{offd}")
            kw_pair_off = self.alloc_raw(f"__kwpair_{offd}", 16)
            self.emit(f"    lea rcx, [rbp{kw_off}]\n    call runtime_new_dict")
            for k, v in kwargs.items():
                koff = self.alloc_temp(f"__kwkey_{offd}_{k}")
                kl = self.get_string_label(k)
                self.emit(
                    f"    mov qword ptr [rbp{koff}], 2\n"
                    f"    lea rax, [{kl}]\n"
                    f"    mov qword ptr [rbp{koff + 8}], rax")
                voff = self.alloc_temp(v)
                self.emit(
                    f"    lea rcx, [rbp{kw_off}]\n"
                    f"    lea rdx, [rbp{koff}]\n"
                    f"    lea r8, [rbp{voff}]\n"
                    f"    call runtime_dict_set")
            self.emit(f"    mov qword ptr [rbp{kw_pair_off}], {nargs}")
            self.emit(
                f"    lea rax, [rbp{kw_off}]\n"
                f"    mov qword ptr [rbp{kw_pair_off + 8}], rax")
        self.emit(f"    lea rcx, [rbp{offd}]")
        if direct_label is not None:
            if nargs > 0:
                self.emit(f"    lea rdx, [rbp{args_arr_off}]")
            else:
                self.emit(f"    xor rdx, rdx")
            self.emit(f"    mov r8, {nargs}\n    call {direct_label}")
        elif kwargs:
            self.emit(f"    lea rdx, [rbp{off_func}]")
            if nargs > 0:
                self.emit(f"    lea r8, [rbp{args_arr_off}]")
            else:
                self.emit(f"    xor r8, r8")
            self.emit(f"    lea r9, [rbp{kw_pair_off}]")
            self.emit("    call runtime_call_kw")
        else:
            self.emit(f"    lea rdx, [rbp{off_func}]")
            if nargs > 0:
                self.emit(f"    lea r8, [rbp{args_arr_off}]")
            else:
                self.emit(f"    xor r8, r8")
            self.emit(f"    mov r9, {nargs}\n    call runtime_call")

    def gen_builtin(self, op):
        kind, dest, args = op
        offd = self.alloc_temp(dest)
        if kind == 'print':
            nargs = len(args)
            if nargs == 0:
                self.emit(
                    f"    mov qword ptr [rbp{offd}], 2\n"
                    f"    lea rax, [{self.get_string_label('')}]\n"
                    f"    mov qword ptr [rbp{offd + 8}], rax")
            else:
                for i, a in enumerate(args):
                    aoff = self.alloc_temp(a)
                    self.emit(f"    lea rcx, [rbp{aoff}]")
                    if i < nargs - 1:
                        self.emit("    call runtime_write")
                        self.emit("    call runtime_write_space")
                    else:
                        self.emit("    call runtime_print")
            self.emit(
                f"    mov qword ptr [rbp{offd}], 4\n"
                f"    mov qword ptr [rbp{offd + 8}], 0")
        elif kind in ('str', 'len', 'int', 'float', 'bool', 'type'):
            if args:
                aoff = self.alloc_temp(args[0])
                self.emit(
                    f"    lea rcx, [rbp{offd}]\n"
                    f"    lea rdx, [rbp{aoff}]\n"
                    f"    call runtime_{kind}")
            else:
                if kind == 'str':
                    self.emit(
                        f"    mov qword ptr [rbp{offd}], 2\n"
                        f"    lea rax, [{self.get_string_label('')}]\n"
                        f"    mov qword ptr [rbp{offd + 8}], rax")
                elif kind == 'len':
                    self.emit(
                        f"    mov qword ptr [rbp{offd}], 0\n"
                        f"    mov qword ptr [rbp{offd + 8}], 0")
                else:
                    self.emit(
                        f"    mov qword ptr [rbp{offd}], 4\n"
                        f"    mov qword ptr [rbp{offd + 8}], 0")
        elif kind == 'range':
            nargs = len(args)
            if nargs == 1:
                aoff = self.alloc_temp(args[0])
                self.emit(
                    f"    lea rcx, [rbp{offd}]\n"
                    f"    lea rdx, [rbp{aoff}]\n"
                    f"    xor r8, r8\n"
                    f"    call runtime_range")
            elif nargs == 2:
                aoff = self.alloc_temp(args[0])
                boff = self.alloc_temp(args[1])
                self.emit(
                    f"    lea rcx, [rbp{offd}]\n"
                    f"    lea rdx, [rbp{aoff}]\n"
                    f"    lea r8, [rbp{boff}]\n"
                    f"    call runtime_range")
            else:
                self.emit(
                    f"    mov qword ptr [rbp{offd}], 4\n"
                    f"    mov qword ptr [rbp{offd + 8}], 0")

    def gen_return(self, op):
        _, src = op
        off = self.alloc_temp(src)
        rtype = getattr(self, 'current_ret_type', None)
        if rtype in self.SCALAR_TYPES:
            tmp = self.alloc_temp(f"__retconv_{off}")
            label = self.get_string_label(rtype)
            self.emit(
                f"    lea rcx, [rbp{tmp}]\n"
                f"    lea rdx, [rbp{off}]\n"
                f"    lea r8, [{label}]\n"
                f"    call runtime_convert")
            off = tmp
        self.emit(
            f"    mov rcx, qword ptr [rbp{self.result_off}]\n"
            f"    mov rax, qword ptr [rbp{off}]\n"
            f"    mov qword ptr [rcx], rax")
        self.emit(
            f"    mov rax, qword ptr [rbp{off + 8}]\n"
            f"    mov qword ptr [rcx + 8], rax")
        self.emit("    leave\n    ret")

