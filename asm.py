    def gen_builtin_call(self, op):
        _, dest, name, args, kwargs = op
        offd = self.alloc_temp(dest)
        if args:
            args_off = self.alloc_raw(f"__bargs_{offd}", len(args) * 8)
            for i, a in enumerate(args):
                aoff = self.alloc_temp(a)
                self.emit(
                    f"    lea rax, [rbp{aoff}]\n"
                    f"    mov qword ptr [rbp{args_off + i * 8}], rax")
        else:
            args_off = 0
        label = self.get_string_label(name)
        self.emit(f"    lea rcx, [rbp{offd}]")
        self.emit(f"    lea rdx, [{label}]")
        if args:
            self.emit(f"    lea r8, [rbp{args_off}]")
        else:
            self.emit("    xor r8, r8")
        self.emit(f"    mov r9, {len(args)}\n    call runtime_builtin_call")

    def gen_global_get(self, op):
        _, dest, name = op
        offd = self.alloc_temp(dest)
        label = self.get_string_label(name)
        if name.startswith('__cap_'):
            # 闭包捕获读：rcx=name，返回槽指针，拷两个 qword 到临时槽
            self.emit(f" lea rcx, [{label}]")
            self.emit(" call runtime_cap_get")
            self.emit(" mov rcx, rax")
            self.emit(f" mov rdx, qword ptr [rcx]")
            self.emit(f" mov qword ptr [rbp{offd}], rdx")
            self.emit(f" mov rdx, qword ptr [rcx + 8]")
            self.emit(f" mov qword ptr [rbp{offd + 8}], rdx")
            return
        self.emit(f" lea rcx, [{label}]\n call get_var")
        self.emit(f" mov rdx, qword ptr [rax]")
        self.emit(f" mov qword ptr [rbp{offd}], rdx")
        self.emit(f" mov rdx, qword ptr [rax + 8]")
        self.emit(f" mov qword ptr [rbp{offd + 8}], rdx")

