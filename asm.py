    def _emit_value_addr(self, temp, reg='rcx'):
        """把 temp 对应的“值地址”装进 reg（局部变量用栈槽，全局用 get_var）。"""
        name = self.temp_var_name.get(temp)
        if name:
            if self.in_function and name in self.local_vars:
                off = self.local_vars[name]
                self.emit(f"    lea rcx, [rbp{off}]\n    call runtime_deref")
                self.emit(f"    mov {reg}, rax")
                return
            label = self.get_string_label(name)
            self.emit(f"    lea {reg}, [{label}]")
            self.emit("    call get_var")
            self.emit(f"    mov {reg}, rax")
            return
        off = self.alloc_temp(temp)
        self.emit(f"    lea {reg}, [rbp{off}]")

