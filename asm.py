    def gen_class(self, op):
        _, name, bases, methods = op
        cls_tmp = f"__cls_{name}"
        cls_off = self.alloc_raw(cls_tmp, 8)
        name_label = self.get_string_label(name)
        self.emit(
            f"    lea rcx, [rbp{cls_off}]\n"
            f"    lea rdx, [{name_label}]\n"
            f"    call runtime_new_class")
        for base in bases:
            base_label = self.get_string_label(base)
            self.emit(f"    lea rcx, [{base_label}]\n    call get_var")
            self.emit("    mov rdx, rax")
            self.emit(f"    mov rcx, qword ptr [rbp{cls_off}]")
            self.emit("    call runtime_class_add_base")
        for mname, minfo in methods.items():
            fn_label = self._method_label(name, mname)
            sig_label = self._make_sig(minfo[1])
            mname_label = self.get_string_label(mname)
            self.emit(
                f"    mov rcx, qword ptr [rbp{cls_off}]\n"
                f"    lea rdx, [{mname_label}]\n"
                f"    lea r8, [{fn_label}]\n"
                f"    lea r9, [{sig_label}]\n"
                f"    call runtime_class_add_method_ex")
        out_off = self.alloc_temp(f"__clsval_{name}")
        self.emit(
            f"    mov qword ptr [rbp{out_off}], 10\n"
            f"    mov rax, qword ptr [rbp{cls_off}]\n"
            f"    mov qword ptr [rbp{out_off + 8}], rax")
        self.emit(f"    lea rcx, [{name_label}]\n    call get_var")
        self.emit(
            f"    mov rcx, qword ptr [rbp{out_off}]\n"
            f"    mov qword ptr [rax], rcx")
        self.emit(
            f"    mov rcx, qword ptr [rbp{out_off + 8}]\n"
            f"    mov qword ptr [rax + 8], rcx")

    def gen_halt(self):
        self.emit("    xor eax, eax\n    leave\n    ret")
