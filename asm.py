import struct
from decimal import Decimal
from class_and_vars import I64, WStr


class AsmGenerator:
    """IR -> MASM 64 位汇编（Windows x64 ABI，无 CRT）"""

    BUILTIN_CALLS = {'print', 'str', 'len',
                     'int', 'float', 'bool', 'type', 'range'}
    SCALAR_TYPES = {'int', 'i64', 'i32', 'float',
                    'double', 'str', 'bool', 'cstr', 'ptr'}
    BINOP_MAGIC = {
        '__add__': 'add', '__sub__': 'sub', '__mul__': 'mul',
        '__div__': 'div', '__floordiv__': 'floordiv', '__mod__': 'mod',
        '__pow__': 'pow', '__eq__': 'eq', '__ne__': 'ne',
        '__lt__': 'lt', '__gt__': 'gt', '__le__': 'le', '__ge__': 'ge',
    }

    def __init__(self, ir, target='exe'):
        self.ir = ir
        self.target = target
        self.lines = []
        self.temp_offset = {}
        self.temp_counter = 0
        self.strings = {}
        self.wstrings = {}
        self.float_consts = {}
        self.label_counter = 0
        self.func_labels = {}
        self.int_funcs = set()
        self.result_off = 0
        self.args_off = 0
        self.argc_off = 0
        self.local_vars = {}
        self.in_function = False
        self.temp_var_name = {}
        self.extra_data = []
        self.sig_counter = 0
        self.func_label_by_id = {}
        self.funcs_with_defaults = set()
        self.dll_specs = {}
        self.struct_specs = []
        self.export_funcs = []
        self.export_symbols = []

    def alloc_raw(self, name, size):
        if name not in self.temp_offset:
            n = (size + 7) // 8
            self.temp_counter += n
            self.temp_offset[name] = -8 * self.temp_counter
        return self.temp_offset[name]

    def alloc_temp(self, name):
        if name not in self.temp_offset:
            self.temp_counter += 2
            self.temp_offset[name] = -8 * self.temp_counter
        return self.temp_offset[name]

    def alloc_local(self, name):
        if name not in self.local_vars:
            self.temp_counter += 2
            self.local_vars[name] = -8 * self.temp_counter
        return self.local_vars[name]

    def emit(self, line):
        self.lines.append(line)

    def new_label(self, prefix="L"):
        self.label_counter += 1
        return f"{prefix}{self.label_counter}"

    def get_string_label(self, s):
        if s not in self.strings:
            self.strings[s] = f"str_{len(self.strings)}"
        return self.strings[s]

    def get_wstring_label(self, s):
        if s not in self.wstrings:
            self.wstrings[s] = f"wstr_{len(self.wstrings)}"
        return self.wstrings[s]

    def get_float_label(self, f):
        key = repr(f)
        if key not in self.float_consts:
            self.float_consts[key] = f"flt_{len(self.float_consts)}"
        return self.float_consts[key]

    @staticmethod
    def _method_label(cls_name, mname):
        return f"func_{cls_name}__{mname}"

    def generate(self):
        for op in self.ir:
            if op[0] == 'struct_def':
                self.struct_specs.append(op)
            elif op[0] == 'dll_import':
                path = op[1]
                for fname, params, ret in op[2]:
                    parts = []
                    for p in params:
                        mod = p[2]
                        parts.append(p[1] + (':' + mod if mod else ''))
                    spec = f"{path}|{fname}|{ret}|" + ';'.join(parts)
                    self.dll_specs[fname] = spec
            elif op[0] == 'exports':
                self.export_funcs = list(op[1])

        func_ops = []
        main_ops = []
        for op in self.ir:
            if op[0] in ('func', 'func_int', 'method_func'):
                func_ops.append(op)
                main_ops.append(op)
            else:
                main_ops.append(op)

        nested_ops = []

        def collect_nested(sub):
            for o in sub:
                if o[0] == 'func':
                    nested_ops.append(o)
                    collect_nested(o[2])
                elif o[0] == 'method_func':
                    nested_ops.append(o)
                    collect_nested(o[3])

        for op in func_ops:
            if op[0] == 'func':
                collect_nested(op[2])
            elif op[0] == 'method_func':
                collect_nested(op[3])

        for op in func_ops + nested_ops:
            if op[0] == 'func_int':
                self.int_funcs.add(op[1])
            elif op[0] == 'func':
                params = op[3]
                needs_bind = bool(op[7]) or any(
                    p.get('varargs') or p.get('kwargs') for p in params)
                if needs_bind:
                    self.funcs_with_defaults.add(op[1])

        self.emit("; MASM 64-bit generated by ECL (no CRT)")

        for name in [
            'get_var', 'get_var_slot',
            'runtime_add', 'runtime_sub', 'runtime_mul', 'runtime_div',
            'runtime_floordiv', 'runtime_mod', 'runtime_pow',
            'runtime_eq', 'runtime_ne', 'runtime_lt', 'runtime_gt',
            'runtime_le', 'runtime_ge',
            'runtime_print', 'runtime_write', 'runtime_write_space',
            'runtime_truthy',
            'runtime_new_function', 'runtime_func_set_defaults',
            'runtime_call',
            'runtime_str', 'runtime_len', 'runtime_int', 'runtime_float',
            'runtime_bool', 'runtime_type', 'runtime_range',
            'runtime_to_i64', 'runtime_to_i32',
            'runtime_new_class', 'runtime_class_add_method',
            'runtime_get_attr', 'runtime_set_attr',
            'runtime_new_list', 'runtime_list_append',
            'runtime_new_dict', 'runtime_dict_set',
            'runtime_get_item', 'runtime_set_item',
            'runtime_setjmp', 'runtime_longjmp',
            'runtime_push_exception', 'runtime_pop_exception',
            'runtime_raise_error', 'runtime_to_bi', 'runtime_store_share',
            'runtime_free', 'runtime_match_eq', 'runtime_is_type',
            'runtime_to_tuple', 'runtime_iter_list', 'runtime_list_extend',
            'runtime_dict_update', 'runtime_expect_len', 'runtime_convert',
            'runtime_using_enter', 'runtime_get_attr_opt',
            'runtime_class_add_base', 'runtime_base_view',
            'runtime_raise_value', 'runtime_reraise', 'runtime_exc_match',
            'runtime_get_exc_value', 'runtime_with_enter',
            'runtime_define_function', 'runtime_class_add_method_ex',
            'runtime_call_kw', 'runtime_call_spread',
            'runtime_builtin_call', 'runtime_new_code',
            'runtime_make_ref', 'runtime_bigint_from_dec',
            'runtime_get_exc_type', 'runtime_neg', 'runtime_invert',
            'runtime_dll_call', 'runtime_dll_register_layouts',
            'runtime_export_from_wide', 'runtime_export_to_wide',
            'runtime_i32_pair', 'runtime_i32_unary',
            'runtime_store_clone', 'runtime_free_item', 'runtime_free_attr',
            'runtime_make_ref_slot', 'runtime_deref',
            'runtime_buffer_address', 'runtime_struct_new',
                'runtime_func_captures', 'runtime_cap_get', 'runtime_cap_set']:
            self.emit(f"EXTERN {name}:PROC")

        self.emit("")
        self.emit(".code")
        self.emit("")

        for op in func_ops:
            if op[0] == 'method_func':
                self.func_labels[(op[1], op[2])] = self._method_label(
                    op[1], op[2])
            elif op[0] == 'func_int':
                self.func_labels[op[1]] = f"func_{op[1]}__int"
            else:
                self.func_labels[op[1]] = f"func_{op[1]}"

        overload_counts = {}
        for op in func_ops:
            if op[0] == 'func':
                overload_counts[op[1]] = overload_counts.get(op[1], 0) + 1
        overload_seen = {}
        for op in func_ops:
            if op[0] != 'func':
                continue
            name = op[1]
            if overload_counts.get(name, 0) > 1:
                idx = overload_seen.get(name, 0)
                overload_seen[name] = idx + 1
                self.func_label_by_id[id(op)] = f"func_{name}__ov{idx}"
                if name in self.func_labels:
                    del self.func_labels[name]
            else:
                self.func_label_by_id[id(op)] = f"func_{name}"

        for op in nested_ops:
            self.nested_counter = getattr(self, 'nested_counter', 0) + 1
            if op[0] == 'func':
                self.func_label_by_id[id(op)] = (
                    f"func_{op[1]}__n{self.nested_counter}")
            else:
                self.func_label_by_id[id(op)] = (
                    f"func_{op[1]}__{op[2]}__n{self.nested_counter}")

        # ★ 闭包捕获：扫描每个 func 定义，收集子函数体里用到的 __cap_ 名。
        # gen_cap_dict 依赖 captures_by_id，没有这段它永远拿空名单直接 return。
        # 嵌套函数（method_func / 更深 func）由 _collect_cap_names 递归覆盖，
        # method_func 的捕获同样走 gen_method_function -> _gen_value_function
        # 之外的 gen_cap_dict 路径时也能命中。
        self.captures_by_id = {}
        for op in func_ops + nested_ops:
            if op[0] == 'func':
                caps = self._collect_cap_names(op[2])
                if caps:
                    self.captures_by_id[id(op)] = sorted(caps)

        for op in func_ops + nested_ops:
            if op[0] == 'method_func':
                self.gen_method_function(op)
            elif op[0] == 'func_int':
                self.gen_int_function(op)
            else:
                self.gen_function(op)

        self.gen_main(main_ops)

        if self.target == 'dll':
            for name, params, ret in self.export_funcs:
                self.gen_export_wrapper(name, params, ret)

        if self.target == 'dll' and self.export_funcs:
            self.emit("")
            self.emit(".data")
            self.emit("ecl_module_inited dq 0")

        if self.strings:
            self.emit("")
            self.emit(".data")
            for s, label in self.strings.items():
                raw = s.encode('utf-8')
                if not raw:
                    # 空字符串兜底
                    self.emit(f'{label} db 0')
                    continue
                byte_list = [str(b) for b in raw] + ['0']
                # UTF-8 + NUL 终止
                chunk_size = 16
                for i in range(0, len(byte_list), chunk_size):
                    chunk = byte_list[i:i + chunk_size]
                    prefix = f'{label} db ' if i == 0 else ' db '
                    self.emit(prefix + ', '.join(chunk))

        if self.wstrings:
            self.emit("")
            self.emit(".data")
            for s, label in self.wstrings.items():
                raw = s.encode('utf-16-le') + b'\x00\x00'
                units = [str(int.from_bytes(raw[i:i + 2], 'little'))
                         for i in range(0, len(raw), 2)]
                chunk_size = 16
                for i in range(0, len(units), chunk_size):
                    chunk = ','.join(units[i:i + chunk_size])
                    prefix = f'{label} dw ' if i == 0 else ' dw '
                    self.emit(prefix + chunk)

        if self.extra_data:
            self.emit("")
            self.emit(".data")
            for line in self.extra_data:
                self.emit(line)

        # ↓↓↓ 新增：浮点常量池定义 ↓↓↓
        if self.float_consts:
            import struct as _struct
            self.emit("")
            self.emit(".data")
            for key, label in self.float_consts.items():
                bits = int.from_bytes(
                    _struct.pack('<d', float(key)), 'little')
                self.emit(f"{label} dq 0x{bits:X}")
        # ↑↑↑

        self.emit("")
        self.emit("END")
        return "\n".join(self.lines)

    def _make_sig(self, params):
        """生成 EclSig 静态数据：count / names / types / varargs / kwargs。"""
        self.sig_counter += 1
        n = self.sig_counter
        sig_label = f"sig_{n}"
        names_label = f"signames_{n}"
        types_label = f"sigtypes_{n}"
        name_refs = [self.get_string_label(p['name']) for p in params]
        type_refs = []
        for p in params:
            t = p.get('type')
            type_refs.append(self.get_string_label(t) if t else '0')
        self.extra_data.append(
            f"{names_label} dq " + (", ".join(name_refs) if name_refs else "0"))
        self.extra_data.append(
            f"{types_label} dq " + (", ".join(type_refs) if type_refs else "0"))
        varargs_index = -1
        kwargs_index = -1
        for i, p in enumerate(params):
            if p.get('varargs'):
                varargs_index = i
            elif p.get('kwargs'):
                kwargs_index = i
        self.extra_data.append(
            f"{sig_label} dq {len(params)}, {names_label}, {types_label}, "
            f"{varargs_index}, {kwargs_index}")
        return sig_label

    # ---------- 函数生成 ----------

    def gen_int_function(self, func_op):
        _, name, sub_code, params, ret_type = func_op
        func_label = f"func_{name}__int"
        old = (self.temp_counter, self.temp_offset, self.local_vars,
               self.in_function, self.temp_var_name)
        self.temp_counter = 0
        self.temp_offset = {}
        self.local_vars = {}
        self.in_function = True
        self.temp_var_name = {}
        self.emit(f"; ---------- 函数 {name}（int 特化） ----------")
        self.emit(f"{func_label} PROC")
        self.emit("    push rbp\n    mov rbp, rsp")
        frame_pos = len(self.lines)
        self.emit("    sub rsp, 0")
        regs = ['rcx', 'rdx', 'r8', 'r9']
        for i, p in enumerate(params):
            self.emit(
                f"    mov qword ptr [rbp{self.alloc_local(p['name'])}], {regs[i]}")
        for op in sub_code:
            if op[0] == 'int_store_var':
                self.alloc_local(op[1])
        for op in sub_code:
            self.gen_int_op(op)
        self.emit("    xor eax, eax\n    leave\n    ret")
        frame_size = ((self.temp_counter * 8 + 15) // 16) * 16
        self.lines[frame_pos] = f"    sub rsp, {frame_size}"
        self.emit(f"{func_label} ENDP\n")
        self.temp_counter, self.temp_offset, self.local_vars, \
            self.in_function, self.temp_var_name = old

    def int_load(self, operand, dst_reg):
        kind, val = operand
        if kind == 'reg':
            slot = self.local_vars.get(val)
            if slot is not None:
                self.emit(f"    mov {dst_reg}, qword ptr [rbp{slot}]")
            else:
                label = self.get_string_label(val)
                self.emit(
                    "    push rax\n    push rcx\n    push rdx\n    push r11")
                self.emit(f"    lea rcx, [{label}]\n    call get_var")
                self.emit("    mov r10, qword ptr [rax + 8]")
                self.emit("    pop r11\n    pop rdx\n    pop rcx\n    pop rax")
                self.emit(f"    mov {dst_reg}, r10")
        elif kind == 'imm':
            self.emit(f"    mov {dst_reg}, {val}")
        elif kind == 'tmp':
            slot = self.alloc_temp(val)
            self.emit(f"    mov {dst_reg}, qword ptr [rbp{slot}]")

    def int_store(self, dest_tmp, src_reg):
        slot = self.alloc_temp(dest_tmp)
        self.emit(f"    mov qword ptr [rbp{slot}], {src_reg}")

    def gen_int_op(self, op):
        kind = op[0]
        if kind in ('int_add', 'int_sub', 'int_mul', 'int_lt', 'int_gt',
                    'int_le', 'int_ge', 'int_eq', 'int_ne'):
            _, dest, lt, rt = op
            self.int_load(lt, 'rax')
            self.int_load(rt, 'rcx')
            if kind == 'int_add':
                self.emit("    add rax, rcx")
            elif kind == 'int_sub':
                self.emit("    sub rax, rcx")
            elif kind == 'int_mul':
                self.emit("    imul rax, rcx")
            else:
                self.emit("    cmp rax, rcx")
                cond = {'int_lt': 'setl', 'int_gt': 'setg', 'int_le': 'setle',
                        'int_ge': 'setge', 'int_eq': 'sete',
                        'int_ne': 'setne'}[kind]
                self.emit(f"    {cond} al\n    movzx rax, al")
            self.int_store(dest, 'rax')
        elif kind == 'int_and':
            _, dest, lt, rt = op
            self.int_load(lt, 'rax')
            self.int_load(rt, 'rcx')
            self.emit("    test rax, rax\n    setne al\n    movzx rax, al")
            self.emit("    test rcx, rcx\n    setne cl\n    movzx rcx, cl")
            self.emit("    and rax, rcx")
            self.int_store(dest, 'rax')
        elif kind == 'int_or':
            _, dest, lt, rt = op
            self.int_load(lt, 'rax')
            self.int_load(rt, 'rcx')
            self.emit("    or rax, rcx\n    setne al\n    movzx rax, al")
            self.int_store(dest, 'rax')
        elif kind == 'int_neg':
            _, dest, src = op
            self.int_load(src, 'rax')
            self.emit("    neg rax")
            self.int_store(dest, 'rax')
        elif kind == 'int_not':
            _, dest, src = op
            self.int_load(src, 'rax')
            self.emit("    test rax, rax\n    sete al\n    movzx rax, al")
            self.int_store(dest, 'rax')
        elif kind in ('int_jz', 'int_jnz'):
            _, cond, label = op
            self.int_load(cond, 'rax')
            self.emit(
                f"    test rax, rax\n    {'jz' if kind == 'int_jz' else 'jnz'} {label}")
        elif kind == 'int_assign':
            _, dest, src = op
            self.int_load(src, 'rax')
            self.int_store(dest, 'rax')
        elif kind == 'int_store_var':
            _, name, src = op
            self.int_load(src, 'rax')
            slot = self.local_vars.get(name)
            if slot is not None:
                self.emit(f"    mov qword ptr [rbp{slot}], rax")
            else:
                label = self.get_string_label(name)
                self.emit("    push rax\n"
                          f"    lea rcx, [{label}]\n    call get_var")
                self.emit("    mov r10, rax\n    pop rax\n"
                          "    mov qword ptr [r10 + 8], rax")
        elif kind in ('int_ret', 'int_ret_zero'):
            if kind == 'int_ret':
                _, src = op
                self.int_load(src, 'rax')
            else:
                self.emit("    xor eax, eax")
            self.emit("    leave\n    ret")
        elif kind == 'int_call':
            _, dest, fname, args = op
            regs = ['rcx', 'rdx', 'r8', 'r9']
            for i, a in enumerate(args):
                self.int_load(a, regs[i])
            self.emit(f"    call func_{fname}__int")
            self.int_store(dest, 'rax')
        elif kind == 'goto':
            _, label = op
            self.emit(f"    jmp {label}")
        elif kind == 'label':
            _, label = op
            self.emit(f"{label}:")
        elif kind == 'halt':
            self.emit("    xor eax, eax\n    leave\n    ret")

    def gen_function(self, func_op):
        _, name, sub_code, params, varargs, kwargs, ret_type, defaults = func_op
        self._gen_value_function(
            self.func_label_by_id.get(id(func_op), f"func_{name}"),
            name, sub_code, params, varargs, kwargs, ret_type, defaults)

    def gen_method_function(self, op):
        _, cls_name, mname, sub_code, params, varargs, kwargs, ret_type, defaults = op
        self._gen_value_function(self._method_label(cls_name, mname),
                                 f"{cls_name}.{mname}", sub_code, params,
                                 varargs, kwargs, ret_type, defaults)

    def _gen_value_function(self, func_label, display_name, sub_code, params,
                            varargs, kwargs, ret_type, defaults):
        old = (self.temp_counter, self.temp_offset, self.local_vars,
               self.in_function, self.temp_var_name)
        self.temp_counter = 0
        self.temp_offset = {}
        self.local_vars = {}
        self.in_function = True
        self.temp_var_name = {}
        self.emit(f"; ---------- 函数 {display_name} ----------")
        self.emit(f"{func_label} PROC")
        self.emit("    push rbp\n    mov rbp, rsp")
        frame_pos = len(self.lines)
        self.emit("    sub rsp, 0")
        self.result_off = self.alloc_temp("__result__")
        self.args_off = self.alloc_temp("__args__")
        self.argc_off = self.alloc_temp("__argc__")
        self.emit(f"    mov qword ptr [rbp{self.result_off}], rcx")
        self.emit(f"    mov qword ptr [rbp{self.args_off}], rdx")
        self.emit(f"    mov qword ptr [rbp{self.argc_off}], r8")
        for i, p in enumerate(params):
            slot = self.alloc_local(p['name'])
            self.emit(f"    mov rdx, qword ptr [rbp{self.args_off}]")
            self.emit(f"    mov rdx, qword ptr [rdx + {i * 8}]")
            self.emit(f"    mov rax, qword ptr [rdx]")
            self.emit(f"    mov qword ptr [rbp{slot}], rax")
            self.emit(f"    mov rax, qword ptr [rdx + 8]")
            self.emit(f"    mov qword ptr [rbp{slot + 8}], rax")
            ptype = p.get('type')
            if ptype in self.SCALAR_TYPES and ptype != 'cstr' \
                    and ptype != 'ptr' \
                    and not p.get('varargs') and not p.get('kwargs'):
                tlabel = self.get_string_label(ptype)
                self.emit(
                    f"    lea rcx, [rbp{slot}]\n"
                    f"    lea rdx, [rbp{slot}]\n"
                    f"    lea r8, [{tlabel}]\n"
                    f"    call runtime_convert")
        old_ret = getattr(self, 'current_ret_type', None)
        self.current_ret_type = ret_type
        for op in sub_code:
            self.gen_op(op)
        self.current_ret_type = old_ret
        self.emit(
            f"    mov rcx, qword ptr [rbp{self.result_off}]\n"
            f"    mov qword ptr [rcx], 3\n"
            f"    mov qword ptr [rcx + 8], 0")
        self.emit("    leave\n    ret")
        frame_size = ((self.temp_counter * 8 + 15) // 16) * 16 + 64 + 8
        self.lines[frame_pos] = f"    sub rsp, {frame_size}"
        self.emit(f"{func_label} ENDP\n")
        self.temp_counter, self.temp_offset, self.local_vars, \
            self.in_function, self.temp_var_name = old

    def gen_main(self, main_ops):
        self.in_function = False
        self.local_vars = {}
        self.temp_var_name = {}
        self.emit("main PROC")
        self.emit("    push rbp\n    mov rbp, rsp")
        frame_pos = len(self.lines)
        self.emit("    sub rsp, 0")
        if self.struct_specs:
            parts = []
            for _, name, fields in self.struct_specs:
                flist = ','.join(f'{t} {n}' for t, n in fields)
                parts.append(f'{name}:{flist}')
            label = self.get_string_label(';'.join(parts))
            self.emit(f"    lea rcx, [{label}]")
            self.emit("    call runtime_dll_register_layouts")
        for op in main_ops:
            if op[0] == 'halt':
                self.gen_halt()
                break
            self.gen_op(op)
        frame_size = ((self.temp_counter * 8 + 15) // 16) * 16 + 64 + 8
        self.lines[frame_pos] = f"    sub rsp, {frame_size}"
        self.emit("    xor eax, eax\n    leave\n    ret")
        self.emit("main ENDP\n")

    def gen_export_wrapper(self, name, params, ret):
        """为 --target dll 生成 C ABI 导出包装。"""
        wrapper = f"ecl_export_{name}"
        self.export_symbols.append((name, wrapper))
        n = len(params)
        save_i = {i: -8 * (i + 1) for i in range(4)}
        save_f = {i: -40 - 8 * i for i in range(4)}
        args_base = -64 - 16 * n
        ptr_base = args_base - 8 * n
        res_off = ptr_base - 16
        frame = ((abs(res_off) + 15) // 16) * 16
        self.emit(f"{wrapper} PROC")
        self.emit("    push rbp\n    mov rbp, rsp")
        self.emit(f"    sub rsp, {frame}")
        for i, reg in enumerate(('rcx', 'rdx', 'r8', 'r9')):
            self.emit(f"    mov qword ptr [rbp{save_i[i]}], {reg}")
        for i in range(4):
            self.emit(f"    movsd qword ptr [rbp{save_f[i]}], xmm{i}")
        init_label = self.new_label("dll_inited")
        self.emit("    cmp qword ptr [ecl_module_inited], 0")
        self.emit(f"    jne {init_label}")
        self.emit("    mov qword ptr [ecl_module_inited], 1")
        self.emit("    call main")
        self.emit(f"{init_label}:")
        if self.struct_specs:
            parts = []
            for _, sname, fields in self.struct_specs:
                flist = ','.join(f'{t} {n}' for t, n in fields)
                parts.append(f'{sname}:{flist}')
            label = self.get_string_label(';'.join(parts))
            self.emit(f"    lea rcx, [{label}]")
            self.emit("    call runtime_dll_register_layouts")

        def src(i, ptype):
            if i < 4:
                if ptype in ('float', 'double'):
                    return f"qword ptr {self._mem(save_f[i])}"
                return f"qword ptr {self._mem(save_i[i])}"
            return f"qword ptr {self._mem(48 + 8 * (i - 4))}"

        for i, p in enumerate(params):
            t = p[1]
            dst = args_base + 16 * i
            if t == 'i64':
                self.emit(f"    mov qword ptr [rbp{dst}], 20")
                self.emit(f"    mov rax, {src(i, t)}")
                self.emit(f"    mov qword ptr [rbp{dst + 8}], rax")
            elif t == 'i32':
                self.emit(f"    mov qword ptr [rbp{dst}], 22")
                self.emit(
                    f"    movsxd rax, dword ptr {self._mem(self._src_off(i, t, save_i, save_f))}")
                self.emit(f"    mov qword ptr [rbp{dst + 8}], rax")
            elif t == 'bool':
                self.emit(f"    mov qword ptr [rbp{dst}], 19")
                self.emit(
                    f"    mov eax, dword ptr {self._mem(self._src_off(i, t, save_i, save_f))}")
                self.emit(f"    mov qword ptr [rbp{dst + 8}], rax")
            elif t == 'float':
                self.emit(f"    mov qword ptr [rbp{dst}], 1")
                off = save_f[i] if i < 4 else 48 + 8 * (i - 4)
                self.emit(f"    movss xmm0, dword ptr {self._mem(off)}")
                self.emit("    cvtss2sd xmm0, xmm0")
                self.emit(f"    movsd qword ptr [rbp{dst + 8}], xmm0")
            elif t == 'double':
                self.emit(f"    mov qword ptr [rbp{dst}], 21")
                off = save_f[i] if i < 4 else 48 + 8 * (i - 4)
                self.emit(f"    mov rax, qword ptr {self._mem(off)}")
                self.emit(f"    mov qword ptr [rbp{dst + 8}], rax")
            elif t == 'str':
                self.emit(f"    mov qword ptr [rbp{dst}], 2")
                if i < 4:
                    self.emit(f"    mov rcx, qword ptr [rbp{save_i[i]}]")
                else:
                    self.emit(
                        f"    mov rcx, qword ptr {self._mem(48 + 8 * (i - 4))}")
                self.emit("    call runtime_export_from_wide")
                self.emit(f"    mov qword ptr [rbp{dst + 8}], rax")
            elif t == 'cstr':
                self.emit(f"    mov qword ptr [rbp{dst}], 2")
                self.emit(f"    mov rax, {src(i, t)}")
                self.emit(f"    mov qword ptr [rbp{dst + 8}], rax")
            else:  # int / ptr
                self.emit(f"    mov qword ptr [rbp{dst}], 0")
                self.emit(f"    mov rax, {src(i, t)}")
                self.emit(f"    mov qword ptr [rbp{dst + 8}], rax")
            self.emit(f"    lea rax, [rbp{dst}]")
            self.emit(f"    mov qword ptr [rbp{ptr_base + 8 * i}], rax")
        label = self.func_labels.get(name, f"func_{name}")
        self.emit(f"    lea rcx, [rbp{res_off}]")
        self.emit(f"    lea rdx, [rbp{ptr_base}]")
        self.emit(f"    mov r8, {n}")
        self.emit(f"    call {label}")
        if ret in ('int', 'i64', 'ptr', 'cstr'):
            self.emit(f"    mov rax, qword ptr [rbp{res_off + 8}]")
        elif ret == 'i32':
            self.emit(f"    mov eax, dword ptr [rbp{res_off + 8}]")
        elif ret == 'bool':
            self.emit(f"    mov eax, dword ptr [rbp{res_off + 8}]")
        elif ret == 'float':
            self.emit(f"    movsd xmm0, qword ptr [rbp{res_off + 8}]")
            self.emit("    cvtsd2ss xmm0, xmm0")
        elif ret == 'double':
            self.emit(f"    movsd xmm0, qword ptr [rbp{res_off + 8}]")
        elif ret == 'str':
            self.emit(f"    lea rcx, [rbp{res_off}]")
            self.emit("    call runtime_export_to_wide")
        else:  # none
            self.emit("    xor eax, eax")
        self.emit("    leave\n    ret")
        self.emit(f"{wrapper} ENDP\n")

    @staticmethod
    def _mem(off):
        return f"[rbp{off}]" if off < 0 else f"[rbp+{off}]"

    @staticmethod
    def _src_off(i, ptype, save_i, save_f):
        if i < 4:
            return save_f[i] if ptype in ('float', 'double') else save_i[i]
        return 48 + 8 * (i - 4)

    def gen_op(self, op):
        kind = op[0]
        if kind in ('func_int', 'method_func'):
            return
        if kind in ('struct_def', 'dll_import', 'exports'):
            return
        if kind == 'const':
            self.gen_const(op)
        elif kind == 'var':
            self.gen_var(op)
        elif kind == 'store':
            self.gen_store(op)
        elif kind == 'ref':
            self.gen_ref(op)
        elif kind == 'assign':
            self.gen_assign(op)
        elif kind in ('add', 'sub', 'mul', 'div', 'floordiv', 'mod', 'pow',
                      'eq', 'ne', 'lt', 'gt', 'le', 'ge'):
            self.gen_binop(op)
        elif kind == 'bor':
            self.gen_bitwise(op, "or")
        elif kind == 'band':
            self.gen_bitwise(op, "and")
        elif kind == 'xor':
            self.gen_bitwise(op, "xor")
        elif kind == 'lshift':
            self.gen_shift(op, "shl")
        elif kind == 'rshift':
            self.gen_shift(op, "shr")
        elif kind == 'neg':
            self.gen_runtime_unary(op, "runtime_neg")
        elif kind == 'invert':
            self.gen_runtime_unary(op, "runtime_invert")
        elif kind == 'not':
            self.gen_not(op)
        elif kind == 'jni':
            pass
        elif kind == 'goto':
            self.gen_goto(op)
        elif kind == 'if_goto':
            self.gen_if_goto(op, jump_if_true=True)
        elif kind == 'if_not_goto':
            self.gen_if_goto(op, jump_if_true=False)
        elif kind == 'jz':
            self.gen_jz(op, jump_if_false=True)
        elif kind == 'jnz':
            self.gen_jz(op, jump_if_false=False)
        elif kind == 'label':
            self.gen_label(op)
        elif kind == 'call':
            self.gen_call(op)
        elif kind in self.BUILTIN_CALLS:
            self.gen_builtin(op)
        elif kind == 'return':
            self.gen_return(op)
        elif kind == 'return_none':
            self.gen_return_const(4)
        elif kind == 'return_null':
            self.gen_return_const(3)
        elif kind == 'new_list':
            self.gen_new_list(op)
        elif kind == 'list_append':
            self.gen_list_append(op)
        elif kind == 'list_extend':
            self.gen_list_extend(op)
        elif kind == 'iter_list':
            self.gen_iter_list(op)
        elif kind == 'to_tuple':
            self.gen_to_tuple(op)
        elif kind == 'dict_update':
            self.gen_dict_update(op, 0)
        elif kind == 'dict_update_strict':
            self.gen_dict_update(op, 1)
        elif kind == 'expect_len':
            self.gen_expect_len(op)
        elif kind == 'match_eq':
            self.gen_match_eq(op)
        elif kind == 'is_type':
            self.gen_is_type(op)
        elif kind == 'convert_type':
            self.gen_convert_type(op)
        elif kind == 'using_enter':
            self.gen_using_enter(op)
        elif kind == 'get_attr_opt':
            self.gen_get_attr_opt(op)
        elif kind == 'base_view':
            self.gen_base_view(op)
        elif kind == 'exc_match':
            self.gen_exc_match(op)
        elif kind == 'current_exc':
            self.gen_current_exc(op)
        elif kind == 'current_exc_type':
            self.gen_current_exc_type(op)
        elif kind == 'reraise':
            self.emit("    call runtime_reraise")
        elif kind == 'raise':
            self.gen_raise(op)
        elif kind == 'raise_error':
            label = self.get_string_label(op[1])
            self.emit(f"    lea rcx, [{label}]\n    call runtime_raise_error")
        elif kind == 'with_enter':
            self.gen_with_enter(op)
        elif kind == 'pop_try':
            self.emit("    call runtime_pop_exception")
        elif kind == 'call_spread':
            self.gen_call_spread(op)
        elif kind == 'builtin_call':
            self.gen_builtin_call(op)
        elif kind == 'global_get':
            self.gen_global_get(op)
        elif kind == 'global_set':
            self.gen_global_set(op)
        elif kind == 'store_share':
            _, name, src = op
            off = self.alloc_temp(src)
            if self.in_function and name in self.local_vars:
                self.emit(f" lea rcx, [rbp{self.local_vars[name]}]")
            else:
                label = self.get_string_label(name)
                self.emit(f" lea rcx, [{label}]\n call get_var")
                self.emit(" mov rcx, rax")
            self.emit(f" lea rdx, [rbp{off}]")
            self.emit(" call runtime_store_share")

        elif kind == 'make_code':
            offd = self.alloc_temp(op[1])
            label = self.func_labels.get(op[2], f"func_{op[2]}")
            self.emit(
                f"    lea rcx, [rbp{offd}]\n"
                f"    lea rdx, [{label}]\n"
                f"    call runtime_new_code")
        elif kind == 'new_dict':
            self.gen_new_dict(op)
        elif kind == 'dict_set':
            self.gen_dict_set(op)
        elif kind == 'get_item':
            self.gen_get_item(op)
        elif kind == 'set_item':
            self.gen_set_item(op)
        elif kind == 'address_of':
            _, dest, src = op
            offd = self.alloc_temp(dest)
            offs = self.alloc_temp(src)
            self.emit(
                f"    lea rcx, [rbp{offd}]\n"
                f"    lea rdx, [rbp{offs}]\n"
                f"    call runtime_buffer_address")
        elif kind == 'struct_new':
            _, dest, name = op
            offd = self.alloc_temp(dest)
            label = self.get_string_label(name)
            self.emit(
                f"    lea rcx, [rbp{offd}]\n"
                f"    lea rdx, [{label}]\n"
                f"    call runtime_struct_new")
        elif kind == 'get_attr':
            self.gen_get_attr(op)
        elif kind == 'set_attr':
            self.gen_set_attr(op)
        elif kind == 'func':
            self.gen_func(op)
        elif kind == 'class':
            self.gen_class(op)
        elif kind == 'to_bi':
            self.gen_to_bi(op)
        elif kind == 'try':
            except_label, finally_label = op[1], op[2]
            env_off = self.alloc_raw(f"__env_{except_label}", 80)
            self.emit(f"    lea rcx, [rbp{env_off}]")
            self.emit(f"    call runtime_setjmp")
            self.emit(f"    test rax, rax")
            self.emit(f"    jnz {except_label}")
            self.emit(f"    lea rcx, [rbp{env_off}]")
            self.emit(f"    call runtime_push_exception")
        elif kind == 'end_try':
            normal_label, finally_label = op[1], op[2]
            self.emit("    call runtime_pop_exception")
            self.emit(f"    jmp {normal_label}")
        elif kind == 'except':
            pass
        elif kind == 'finally':
            pass
        elif kind == 'halt':
            self.gen_halt()
        elif kind == 'free':
            self.gen_free(op)
        elif kind == 'free_var':
            self.gen_free_var(op)
        elif kind == 'free_item':
            self.gen_free_item(op)
        elif kind == 'free_attr':
            self.gen_free_attr(op)
        else:
            raise NotImplementedError(
                f"AOT 后端暂不支持指令 '{kind}'（该特性目前仅解释器支持）")

    def gen_free(self, op):
        _, dest, args = op
        offd = self.alloc_temp(dest)
        if args:
            name = self.temp_var_name.get(args[0])
            if name:
                if self.in_function and name in self.local_vars:
                    self.emit(f"    lea rcx, [rbp{self.local_vars[name]}]")
                else:
                    label = self.get_string_label(name)
                    self.emit(f"    lea rcx, [{label}]")
                    self.emit("    call get_var_slot")
                self.emit("    mov rcx, rax")
                self.emit("    call runtime_free")
            else:
                aoff = self.alloc_temp(args[0])
                self.emit(f"    lea rcx, [rbp{aoff}]")
                self.emit("    call runtime_free")
        self.emit(
            f"    mov qword ptr [rbp{offd}], 3\n"
            f"    mov qword ptr [rbp{offd + 8}], 0")

    def gen_free_var(self, op):
        _, dest, name = op
        offd = self.alloc_temp(dest)
        if self.in_function and name in self.local_vars:
            self.emit(f"    lea rcx, [rbp{self.local_vars[name]}]")
        else:
            label = self.get_string_label(name)
            self.emit(f"    lea rcx, [{label}]")
            self.emit("    call get_var_slot")
        self.emit("    mov rcx, rax")
        self.emit("    call runtime_free")
        self.emit(
            f"    mov qword ptr [rbp{offd}], 3\n"
            f"    mov qword ptr [rbp{offd + 8}], 0")

    def gen_free_item(self, op):
        _, dest, container, idx = op
        offd = self.alloc_temp(dest)
        offc = self.alloc_temp(container)
        offi = self.alloc_temp(idx)
        self.emit(
            f"    lea rcx, [rbp{offc}]\n"
            f"    lea rdx, [rbp{offi}]\n"
            f"    call runtime_free_item")
        self.emit(
            f"    mov qword ptr [rbp{offd}], 3\n"
            f"    mov qword ptr [rbp{offd + 8}], 0")

    def gen_free_attr(self, op):
        _, dest, obj, name = op
        offd = self.alloc_temp(dest)
        offo = self.alloc_temp(obj)
        nlabel = self.get_string_label(name)
        self.emit(
            f"    lea rcx, [rbp{offo}]\n"
            f"    lea rdx, [{nlabel}]\n"
            f"    call runtime_free_attr")
        self.emit(
            f"    mov qword ptr [rbp{offd}], 3\n"
            f"    mov qword ptr [rbp{offd + 8}], 0")

    def gen_to_bi(self, op):
        _, dest, src = op
        offs = self.alloc_temp(src)
        offd = self.alloc_temp(dest)
        self.emit(f"    lea rcx, [rbp{offd}]")
        self.emit(f"    lea rdx, [rbp{offs}]")
        self.emit(f"    call runtime_to_bi")

    def _emit_int_payload(self, off, value):
        if -(1 << 31) <= value < (1 << 31):
            self.emit(
                f"    mov qword ptr [rbp{off}], 0\n"
                f"    mov qword ptr [rbp{off + 8}], {value}")
        else:
            self.emit(
                f"    mov qword ptr [rbp{off}], 0\n"
                f"    mov rax, {value}\n"
                f"    mov qword ptr [rbp{off + 8}], rax")

    def gen_const(self, op):
        _, dest, value = op
        off = self.alloc_temp(dest)
        if isinstance(value, bool):
            self.emit(
                f"    mov qword ptr [rbp{off}], 19\n"
                f"    mov qword ptr [rbp{off + 8}], {int(value)}")
        elif isinstance(value, I64):
            self._emit_int_payload(off, int(value))
        elif isinstance(value, Decimal):
            flabel = self.get_float_label(float(value))
            self.emit(
                f"    mov qword ptr [rbp{off}], 21\n"
                f"    mov rax, qword ptr [{flabel}]\n"
                f"    mov qword ptr [rbp{off + 8}], rax")
        elif isinstance(value, int):
            if -(1 << 63) <= value < (1 << 63):
                self._emit_int_payload(off, value)
            else:
                slabel = self.get_string_label(str(value))
                self.emit(
                    f"    lea rcx, [rbp{off}]\n"
                    f"    lea rdx, [{slabel}]\n"
                    f"    call runtime_bigint_from_dec")
        elif isinstance(value, float):
            flabel = self.get_float_label(value)
            self.emit(
                f"    mov qword ptr [rbp{off}], 1\n"
                f"    mov rax, qword ptr [{flabel}]\n"
                f"    mov qword ptr [rbp{off + 8}], rax")
        elif isinstance(value, WStr):
            slabel = self.get_wstring_label(str(value))
            self.emit(
                f"    mov qword ptr [rbp{off}], 26\n"
                f"    lea rax, [{slabel}]\n"
                f"    mov qword ptr [rbp{off + 8}], rax")
        elif isinstance(value, str):
            slabel = self.get_string_label(value)
            self.emit(
                f"    mov qword ptr [rbp{off}], 2\n"
                f"    lea rax, [{slabel}]\n"
                f"    mov qword ptr [rbp{off + 8}], rax")
        elif value is None:
            self.emit(
                f"    mov qword ptr [rbp{off}], 4\n"
                f"    mov qword ptr [rbp{off + 8}], 0")
        else:
            self.emit(
                f"    mov qword ptr [rbp{off}], 3\n"
                f"    mov qword ptr [rbp{off + 8}], 0")

    def gen_var(self, op):
        _, dest, name = op
        off = self.alloc_temp(dest)
        self.temp_var_name[dest] = name
        if self.in_function and name in self.local_vars:
            slot = self.local_vars[name]
            self.emit(f"    lea rcx, [rbp{slot}]\n    call runtime_deref")
            self.emit("    mov rcx, rax")
            self.emit(
                f"    mov rax, qword ptr [rcx]\n"
                f"    mov qword ptr [rbp{off}], rax")
            self.emit(
                f"    mov rax, qword ptr [rcx + 8]\n"
                f"    mov qword ptr [rbp{off + 8}], rax")
        else:
            label = self.get_string_label(name)
            self.emit(
                f"    lea rcx, [{label}]\n"
                f"    call get_var\n"
                f"    mov rcx, rax")
            self.emit(
                f"    mov rax, qword ptr [rcx]\n"
                f"    mov qword ptr [rbp{off}], rax")
            self.emit(
                f"    mov rax, qword ptr [rcx + 8]\n"
                f"    mov qword ptr [rbp{off + 8}], rax")

    def gen_store(self, op):
        _, name, src = op
        off = self.alloc_temp(src)
        if self.in_function and name in self.local_vars:
            slot = self.local_vars[name]
            self.emit(f"    lea rcx, [rbp{slot}]")
            self.emit(f"    lea rdx, [rbp{off}]")
            self.emit("    call runtime_store_clone")
        else:
            label = self.get_string_label(name)
            self.emit(f"    lea rcx, [{label}]\n    call get_var")
            self.emit("    mov rcx, rax")
            self.emit(f"    lea rdx, [rbp{off}]")
            self.emit("    call runtime_store_clone")

    def _var_slot_addr(self, name, reg):
        if self.in_function and name in self.local_vars:
            self.emit(f"    lea {reg}, [rbp{self.local_vars[name]}]")
        else:
            label = self.get_string_label(name)
            self.emit(f"    lea rcx, [{label}]\n    call get_var_slot")
            self.emit(f"    mov {reg}, rax")

    def gen_ref(self, op):
        _, name, src_name = op
        tmp = self.alloc_raw(f"__ref_target_{name}", 8)
        self._var_slot_addr(src_name, 'rdx')
        self.emit(f"    mov qword ptr [rbp{tmp}], rdx")
        self._var_slot_addr(name, 'rcx')
        self.emit(f"    mov rdx, qword ptr [rbp{tmp}]")
        self.emit("    call runtime_make_ref_slot")

    def gen_assign(self, op):
        _, dest, src = op
        offd = self.alloc_temp(dest)
        offs = self.alloc_temp(src)
        self.emit(
            f"    mov rax, qword ptr [rbp{offs}]\n"
            f"    mov qword ptr [rbp{offd}], rax")
        self.emit(
            f"    mov rax, qword ptr [rbp{offs + 8}]\n"
            f"    mov qword ptr [rbp{offd + 8}], rax")

    def gen_binop(self, op):
        _, dest, src1, src2 = op
        kind = op[0]
        off1 = self.alloc_temp(src1)
        off2 = self.alloc_temp(src2)
        offd = self.alloc_temp(dest)
        runtime_label = self.new_label("runtime")
        end_label = self.new_label("end")
        if kind in ('add', 'sub', 'mul', 'lt', 'gt', 'le', 'ge', 'eq', 'ne'):
            self.emit(f"    mov rax, qword ptr [rbp{off1}]")
            self.emit(f"    test rax, rax")
            self.emit(f"    jnz {runtime_label}")
            self.emit(f"    mov rcx, qword ptr [rbp{off2}]")
            self.emit(f"    test rcx, rcx")
            self.emit(f"    jnz {runtime_label}")
            self.emit(f"    mov rax, qword ptr [rbp{off1 + 8}]")
            if kind == 'add':
                self.emit(f"    add rax, qword ptr [rbp{off2 + 8}]")
            elif kind == 'sub':
                self.emit(f"    sub rax, qword ptr [rbp{off2 + 8}]")
            elif kind == 'mul':
                self.emit(f"    imul rax, qword ptr [rbp{off2 + 8}]")
            else:
                self.emit(f"    cmp rax, qword ptr [rbp{off2 + 8}]")
                cond = {'lt': 'setl', 'gt': 'setg', 'le': 'setle',
                        'ge': 'setge', 'eq': 'sete', 'ne': 'setne'}[kind]
                self.emit(f"    {cond} al\n    movzx rax, al")
            self.emit(
                f"    mov qword ptr [rbp{offd}], "
                f"{19 if kind in ('lt', 'gt', 'le', 'ge', 'eq', 'ne') else 0}\n"
                f"    mov qword ptr [rbp{offd + 8}], rax\n"
                f"    jmp {end_label}")
            self.emit(f"{runtime_label}:")
            self.emit(
                f"    lea rcx, [rbp{offd}]\n"
                f"    lea rdx, [rbp{off1}]\n"
                f"    lea r8, [rbp{off2}]\n"
                f"    call runtime_{kind}")
            self.emit(f"{end_label}:")
        else:  # div, floordiv, mod, pow：全部走 runtime
            self.emit(
                f"    lea rcx, [rbp{offd}]\n"
                f"    lea rdx, [rbp{off1}]\n"
                f"    lea r8, [rbp{off2}]\n"
                f"    call runtime_{kind}")

